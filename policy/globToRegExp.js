// `**` cualquier cosa (incluido "/"), `*` y `?` sin "/".
// "**/" también casa con nada, para que "**/.git/**" cubra ".git/config".
const globToRegExp = (glob) => {
	let source = "";
	for (let i = 0; i < glob.length; i++) {
		const char = glob[i];
		if (char === "*" && glob[i + 1] === "*") {
			if (glob[i + 2] === "/") {
				source += "(?:.*/)?";
				i += 2;
			} else {
				source += ".*";
				i += 1;
			}
		} else if (char === "*") source += "[^/]*";
		else if (char === "?") source += "[^/]";
		else source += char.replace(/[.+^${}()|[\]\\]/g, "\\$&");
	}
	return new RegExp(`^${source}$`);
};

module.exports = globToRegExp;
